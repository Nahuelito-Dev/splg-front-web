/** Se compara normalizada (NFKC, sin mayúsculas ni espacios), igual que el back. */
export const isCommonPassword = (value: string): boolean =>
  COMMON_PASSWORDS.has(value.normalize('NFKC').toLowerCase().replace(/\s+/g, ''));

